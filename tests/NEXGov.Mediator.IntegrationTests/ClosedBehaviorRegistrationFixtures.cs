    public Task Process(ComplexPing request, CancellationToken cancellationToken)
    {
        _log.Add("Pre");
        return Task.CompletedTask;
    }
}

public sealed class ComplexPostProcessor : IRequestPostProcessor<ComplexPing, ComplexBehaviorResponse<string>>
{
    private readonly List<string> _log;

